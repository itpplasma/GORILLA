program generate_cell_kernels
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, num, operator(+), operator(*), &
        operator(/), operator(**)
    use fortsym_string, only: str_t, str, chars
    use fortsym_kernel_ir, only: kernel_ir_t, lower_kernel_ir
    use fortsym_kernel_emit, only: kernel_emit_spec_t, emit_fortran_kernel_ir, &
        emit_cuda_device_ir, TARGET_FORTRAN_CPU, &
        TARGET_CUDA
    implicit none

    type(arena_t), target :: arena
    integer :: fu, cu, order
    character(4096) :: directory

    call get_command_argument(1, directory)
    if (len_trim(directory) == 0) error stop 'supply the output directory'
    call arena%init()
    open (newunit=fu, file=trim(directory)//'/gorilla_cell_generated.f90', &
        status='replace', action='write')
    open (newunit=cu, file=trim(directory)//'/gorilla_cell_generated.cuh', &
        status='replace', action='write')
    write (fu, '(a)') '! Generated by gen/generate_cell_kernels.f90. Do not edit.'
    write (fu, '(a)') 'module gorilla_cell_generated'
    write (fu, '(a)') 'use, intrinsic :: iso_fortran_env, only: real64'
    write (fu, '(a)') 'implicit none'
    write (fu, '(a)') 'private'
    write (fu, '(a)') 'public :: gorilla_affine_coefficients2, gorilla_poly_evaluate2'
    write (fu, '(a)') 'public :: gorilla_poly_step1, gorilla_poly_step2, &'
    write (fu, '(a)') '          gorilla_poly_step3, gorilla_poly_step4'
    write (fu, '(a)') 'contains'
    write (cu, '(a)') '// Generated by gen/generate_cell_kernels.f90. Do not edit.'
    write (cu, '(a)') '#pragma once'
    call emit_affine()
    call emit_evaluate()
    do order = 1, 4
        call emit_step(order)
    end do
    write (fu, '(a)') 'end module gorilla_cell_generated'
    close (fu)
    close (cu)

contains

    subroutine emit_affine()
        type(expr_t) :: a(4, 4), b(4), z(4), first(4), second(4), roots(12)
        type(str_t) :: args(24), outputs(12)
        integer :: i, j, k
        k = 0
        do j = 1, 4
            do i = 1, 4
                k = k + 1
                args(k) = str('a'//itoa(k))
                a(i, j) = sym(arena, chars(args(k)))
            end do
        end do
        do i = 1, 4
            args(16 + i) = str('b'//itoa(i))
            args(20 + i) = str('z'//itoa(i))
            b(i) = sym(arena, chars(args(16 + i)))
            z(i) = sym(arena, chars(args(20 + i)))
        end do
        do i = 1, 4
            first(i) = b(i)
            do j = 1, 4
                first(i) = first(i) + a(i, j)*z(j)
            end do
        end do
        do i = 1, 4
            second(i) = num(arena, 0)
            do j = 1, 4
                second(i) = second(i) + a(i, j)*first(j)/2
            end do
        end do
        roots(1:4) = z
        roots(5:8) = first
        roots(9:12) = second
        do i = 1, 12
            outputs(i) = str('c'//itoa(i))
        end do
        call emit('gorilla_affine2_scalar', args, outputs, roots, .true.)
        write (fu, '(a)') 'pure subroutine gorilla_affine_coefficients2(amat,b,z,coef)'
        write (fu, '(a)') 'real(real64), intent(in) :: amat(4,4),b(4),z(4)'
        write (fu, '(a)') 'real(real64), intent(out) :: coef(4,3)'
        write (fu, '(a)') 'call gorilla_affine2_scalar( &'
        do j = 1, 4
            write (fu, '(a)') 'amat(1,'//itoa(j)//'),amat(2,'//itoa(j)// &
                '),amat(3,'//itoa(j)//'),amat(4,'//itoa(j)//'), &'
        end do
        write (fu, '(a)') 'b(1),b(2),b(3),b(4),z(1),z(2),z(3),z(4), &'
        write (fu, '(a)') 'coef(1,1),coef(2,1),coef(3,1),coef(4,1), &'
        write (fu, '(a)') 'coef(1,2),coef(2,2),coef(3,2),coef(4,2), &'
        write (fu, '(a)') 'coef(1,3),coef(2,3),coef(3,3),coef(4,3))'
        write (fu, '(a)') 'end subroutine gorilla_affine_coefficients2'
        write (cu, '(a)') &
            '__device__ __forceinline__ void gorilla_affine_coefficients2('
        write (cu, '(a)') &
            'const double *amat,const double *b,const double *z,double *coef) {'
        write (cu, '(a)') 'gorilla_affine2_scalar('
        do j = 0, 3
            write (cu, '(a)') 'amat['//itoa(4*j)//'],amat['//itoa(4*j+1)// &
                '],amat['//itoa(4*j+2)//'],amat['//itoa(4*j+3)//'],'
        end do
        write (cu, '(a)') 'b[0],b[1],b[2],b[3],z[0],z[1],z[2],z[3],'
        write (cu, '(a)') '&coef[0],&coef[1],&coef[2],&coef[3],&coef[4],&coef[5],'
        write (cu, '(a)') '&coef[6],&coef[7],&coef[8],&coef[9],&coef[10],&coef[11]);'
        write (cu, '(a)') '}'
    end subroutine emit_affine

    subroutine emit_evaluate()
        type(expr_t) :: c(3), tau, roots(1)
        type(str_t) :: args(4), outputs(1)
        integer :: i
        args = [str('c0'), str('c1'), str('c2'), str('tau')]
        do i = 1, 3
            c(i) = sym(arena, chars(args(i)))
        end do
        tau = sym(arena, 'tau')
        roots(1) = c(1) + tau*(c(2) + tau*c(3))
        outputs = [str('value')]
        call emit('gorilla_evaluate2_scalar', args, outputs, roots, .true.)
        write (fu, '(a)') 'pure subroutine gorilla_poly_evaluate2(coef,tau,zout)'
        write (fu, '(a)') 'real(real64), intent(in) :: coef(4,3),tau'
        write (fu, '(a)') 'real(real64), intent(out) :: zout(4)'
        write (fu, '(a)') 'integer :: i'
        write (fu, '(a)') 'do i=1,4'
        write (fu, '(a)') &
            'call gorilla_evaluate2_scalar(coef(i,1),coef(i,2),coef(i,3),tau,zout(i))'
        write (fu, '(a)') 'end do'
        write (fu, '(a)') 'end subroutine gorilla_poly_evaluate2'
        write (cu, '(a)') '__device__ __forceinline__ void gorilla_poly_evaluate2('
        write (cu, '(a)') 'const double *coef,double tau,double *zout) {'
        write (cu, '(a)') 'for(int i=0;i<4;++i) {'
        write (cu, '(a)') &
            'gorilla_evaluate2_scalar(coef[i],coef[i+4],coef[i+8],tau,&zout[i]);'
        write (cu, '(a)') '}'
        write (cu, '(a)') '}'
    end subroutine emit_evaluate

    subroutine emit_step(order)
        integer, intent(in) :: order
        type(str_t) :: args(4), outputs(1)
        type(expr_t) :: tau, root(1), z, b, az
        character(:), allocatable :: names, signature, declaration, left, right
        integer :: stage, factorial
        z = sym(arena, 'z')
        b = sym(arena, 'b')
        az = sym(arena, 'az')
        tau = sym(arena, 'tau')
        factorial = 1
        do stage = 1, order
            factorial = factorial*stage
        end do
        root(1) = z + (tau**order/factorial)*(b + az)
        args = [str('z'),str('b'),str('az'),str('tau')]
        outputs = [str('value')]
        call emit('gorilla_step'//itoa(order)//'_scalar', args, outputs, root, .false.)
        names = 'z,b,az'
        declaration = 'z(4),b(4),az(4)'
        if (order >= 2) then
            names = names//',ab,a2z'
            declaration = declaration//',ab(4),a2z(4)'
        end if
        if (order >= 3) then
            names = names//',a2b,a3z'
            declaration = declaration//',a2b(4),a3z(4)'
        end if
        if (order >= 4) then
            names = names//',a3b,a4z'
            declaration = declaration//',a3b(4),a4z(4)'
        end if
        signature = 'gorilla_poly_step'//itoa(order)
        write (fu, '(a)') 'pure subroutine '//signature//'('//names//',tau,zout)'
        write (fu, '(a)') 'real(real64), intent(in) :: '//declaration//',tau'
        write (fu, '(a)') 'real(real64), intent(out) :: zout(4)'
        write (fu, '(a)') 'real(real64) :: stage(4,0:'//itoa(order)//')'
        write (fu, '(a)') 'integer :: i'
        write (fu, '(a)') 'stage(:,0)=z'
        write (fu, '(a)') 'do i=1,4'
        do stage = 1, order
            select case(stage)
            case(1)
                left = 'b(i)'
                right = 'az(i)'
            case(2)
                left = 'ab(i)'
                right = 'a2z(i)'
            case(3)
                left = 'a2b(i)'
                right = 'a3z(i)'
            case(4)
                left = 'a3b(i)'
                right = 'a4z(i)'
            end select
            write (fu, '(a)') 'call gorilla_step'//itoa(stage)//'_scalar( &'
            write (fu, '(a)') 'stage(i,'//itoa(stage-1)//'),'//left//','//right// &
                ',tau,stage(i,'//itoa(stage)//'))'
        end do
        write (fu, '(a)') 'end do'
        write (fu, '(a)') 'zout=stage(:,'//itoa(order)//')'
        write (fu, '(a)') 'end subroutine '//signature
    end subroutine emit_step

    subroutine emit(name, args, outputs, roots, cuda)
        character(*), intent(in) :: name
        type(str_t), intent(in) :: args(:), outputs(:)
        type(expr_t), intent(in) :: roots(:)
        logical, intent(in) :: cuda
        type(kernel_ir_t) :: ir
        type(kernel_emit_spec_t) :: spec
        type(str_t) :: source
        logical :: ok
        character(:), allocatable :: message
        call lower_kernel_ir(roots, ir, ok, message)
        if (.not. ok) then
            print *, message
            error stop 'cannot lower cell kernels'
        end if
        spec%name = str(name)
        spec%args = args
        spec%outputs = outputs
        spec%temp_prefix = str('t')
        spec%generator = str('gen/generate_cell_kernels.f90')
        spec%regenerate_command = str('generate_cell_kernels SRC/generated')
        spec%pure_procedure = .true.
        spec%policy%small_power_limit = 4
        spec%target = TARGET_FORTRAN_CPU
        source = emit_fortran_kernel_ir(ir, spec, ok, message)
        if (.not. ok) then
            print *, message
            error stop 'cannot emit Fortran cell kernels'
        end if
        write (fu, '(a)') chars(source)
        if (cuda) then
            spec%target = TARGET_CUDA
            source = emit_cuda_device_ir(ir, spec, ok, message)
            if (.not. ok) then
                print *, message
                error stop 'cannot emit CUDA cell kernels'
            end if
            write (cu, '(a)') chars(source)
        end if
    end subroutine emit

    function itoa(value) result(text)
        integer, intent(in) :: value
        character(:), allocatable :: text
        character(16) :: buffer
        write (buffer, '(i0)') value
        text = trim(buffer)
    end function itoa

end program generate_cell_kernels
