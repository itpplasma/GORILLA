program generate_gpu_physics
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, num, operator(+), operator(-), &
        operator(*), operator(/)
    use fortsym_string, only: str_t, str, chars
    use fortsym_kernel_ir, only: kernel_ir_t, lower_kernel_ir
    use fortsym_kernel_emit, only: kernel_emit_spec_t, emit_fortran_kernel_ir, &
        emit_cuda_device_ir, TARGET_FORTRAN_CPU, &
        TARGET_CUDA
    implicit none

    type(arena_t), target :: arena
    character(4096) :: directory
    integer :: cuda_unit, fortran_unit

    call get_command_argument(1, directory)
    if (len_trim(directory) == 0) error stop 'supply the generated-source directory'
    call arena%init()
    open (newunit=cuda_unit, file=trim(directory)//'/gorilla_cuda_physics.cuh', &
        status='replace', action='write')
    open (newunit=fortran_unit, file=trim(directory)//'/gorilla_cuda_physics.f90', &
        status='replace', action='write')
    write (cuda_unit, '(a)') '// Generated by gen/generate_gpu_physics.f90. Do not edit.'
    write (cuda_unit, '(a)') '#pragma once'
    write (fortran_unit, '(a)') '! Generated by gen/generate_gpu_physics.f90. Do not edit.'
    write (fortran_unit, '(a)') 'module gorilla_cuda_physics_generated'
    write (fortran_unit, '(a)') 'implicit none'
    write (fortran_unit, '(a)') 'contains'
    call emit_cell_system()
    call emit_face()
    call emit_distance()
    call emit_normal_velocity()
    write (fortran_unit, '(a)') 'end module gorilla_cuda_physics_generated'
    close (cuda_unit)
    close (fortran_unit)

contains

    subroutine emit_cell_system()
        type(expr_t) :: z(3), vpar, perpinv, cm_over_e, clight, sign_rhs
        type(expr_t) :: bmod1, gb(3), phi1, gphi(3), curlh(3), gbxh1(3), gphixh1(3)
        type(expr_t) :: gbxcurla, gphixcurla, alpha(3, 3), beta(3, 3)
        type(expr_t) :: spalpha, spbeta, curla(3), bmod, phi, k1, k3
        type(expr_t) :: matrix(4, 4), affine(4), roots(20)
        type(str_t), allocatable :: args(:), outputs(:)
        integer :: i, j, k

        allocate (args(50), outputs(20))
        args = [str('z0'), str('z1'), str('z2'), str('vpar'), str('perpinv'), &
            str('cm_over_e'), str('clight'), str('sign_rhs'), str('bmod1'), &
            str('gb0'), str('gb1'), str('gb2'), str('phi1'), str('gphi0'), &
            str('gphi1'), str('gphi2'), str('curlh0'), str('curlh1'), &
            str('curlh2'), str('gbxh10'), str('gbxh11'), str('gbxh12'), &
            str('gphixh10'), str('gphixh11'), str('gphixh12'), &
            str('gbxcurla'), str('gphixcurla'), str('alpha00'), &
            str('alpha10'), str('alpha20'), str('alpha01'), str('alpha11'), &
            str('alpha21'), str('alpha02'), str('alpha12'), str('alpha22'), &
            str('beta00'), str('beta10'), str('beta20'), str('beta01'), &
            str('beta11'), str('beta21'), str('beta02'), str('beta12'), &
            str('beta22'), str('spalpha'), str('spbeta'), str('curla0'), &
            str('curla1'), str('curla2')]
        do i = 1, 3
            z(i) = sym(arena, chars(args(i)))
            gb(i) = sym(arena, chars(args(9 + i)))
            gphi(i) = sym(arena, chars(args(13 + i)))
            curlh(i) = sym(arena, chars(args(16 + i)))
            gbxh1(i) = sym(arena, chars(args(19 + i)))
            gphixh1(i) = sym(arena, chars(args(22 + i)))
            curla(i) = sym(arena, chars(args(47 + i)))
        end do
        vpar = sym(arena, 'vpar')
        perpinv = sym(arena, 'perpinv')
        cm_over_e = sym(arena, 'cm_over_e')
        clight = sym(arena, 'clight')
        sign_rhs = sym(arena, 'sign_rhs')
        bmod1 = sym(arena, 'bmod1')
        phi1 = sym(arena, 'phi1')
        gbxcurla = sym(arena, 'gbxcurla')
        gphixcurla = sym(arena, 'gphixcurla')
        spalpha = sym(arena, 'spalpha')
        spbeta = sym(arena, 'spbeta')
        k = 27
        do j = 1, 3
            do i = 1, 3
                k = k + 1
                alpha(i, j) = sym(arena, chars(args(k)))
                beta(i, j) = sym(arena, chars(args(k + 9)))
            end do
        end do
        bmod = bmod1
        phi = phi1
        do i = 1, 3
            bmod = bmod + gb(i)*z(i)
            phi = phi + gphi(i)*z(i)
        end do
        k1 = -2*perpinv*bmod + vpar*vpar + 2*perpinv*bmod1
        k3 = phi1 - phi
        matrix = num(arena, 0)
        do j = 1, 3
            do i = 1, 3
                matrix(i, j) = sign_rhs*(perpinv*cm_over_e*alpha(i, j) &
                    - clight*beta(i, j))
            end do
        end do
        do i = 1, 3
            matrix(i, 4) = sign_rhs*curla(i)
            affine(i) = sign_rhs*(cm_over_e*(k1*curlh(i) + perpinv*gbxh1(i)) &
                - clight*(2*k3*curlh(i) + gphixh1(i)))
        end do
        matrix(4, 4) = sign_rhs*(perpinv*cm_over_e*spalpha - clight*spbeta)
        affine(4) = sign_rhs*(perpinv*gbxcurla - clight/cm_over_e*gphixcurla)
        roots(1:16) = reshape(matrix, [16])
        roots(17:20) = affine
        do i = 1, 16
            outputs(i) = str('a'//integer_text(i - 1))
        end do
        do i = 1, 4
            outputs(16 + i) = str('b'//integer_text(i - 1))
        end do
        call emit('gorilla_cell_system', args, outputs, roots)
    end subroutine emit_cell_system

    subroutine emit_face()
        type(str_t) :: args(13), outputs(3)
        type(expr_t) :: n(3), offset, z(3), first(3), second(3), roots(3)
        integer :: i
        args = [str('n0'), str('n1'), str('n2'), str('offset'), str('z0'), &
            str('z1'), str('z2'), str('first0'), str('first1'), &
            str('first2'), str('second0'), str('second1'), str('second2')]
        do i = 1, 3
            n(i) = sym(arena, chars(args(i)))
            z(i) = sym(arena, chars(args(4 + i)))
            first(i) = sym(arena, chars(args(7 + i)))
            second(i) = sym(arena, chars(args(10 + i)))
        end do
        offset = sym(arena, 'offset')
        roots = num(arena, 0)
        roots(1) = offset
        do i = 1, 3
            roots(1) = roots(1) + n(i)*z(i)
            roots(2) = roots(2) + n(i)*first(i)
            roots(3) = roots(3) + 2*n(i)*second(i)
        end do
        outputs = [str('distance'), str('linear'), str('quadratic')]
        call emit('gorilla_face_coefficients2', args, outputs, roots)
    end subroutine emit_face

    subroutine emit_distance()
        type(str_t) :: args(7), outputs(1)
        type(expr_t) :: root(1)
        integer :: i
        args = [str('n0'), str('n1'), str('n2'), str('offset'), &
            str('z0'), str('z1'), str('z2')]
        root(1) = sym(arena, 'offset')
        do i = 1, 3
            root(1) = root(1) + sym(arena, chars(args(i))) &
                *sym(arena, chars(args(4 + i)))
        end do
        outputs = [str('distance')]
        call emit('gorilla_plane_distance', args, outputs, root)
    end subroutine emit_distance

    subroutine emit_normal_velocity()
        type(str_t) :: args(10), outputs(1)
        type(expr_t) :: root(1), tau
        integer :: i
        args = [str('n0'), str('n1'), str('n2'), str('first0'), str('first1'), &
            str('first2'), str('second0'), str('second1'), str('second2'), str('tau')]
        tau = sym(arena, 'tau')
        root = num(arena, 0)
        do i = 1, 3
            root(1) = root(1) + sym(arena, chars(args(i))) &
                *(sym(arena, chars(args(3 + i))) &
                + 2*tau*sym(arena, chars(args(6 + i))))
        end do
        outputs = [str('normal_velocity')]
        call emit('gorilla_normal_velocity2', args, outputs, root)
    end subroutine emit_normal_velocity

    subroutine emit(name, args, outputs, roots)
        character(*), intent(in) :: name
        type(str_t), intent(in) :: args(:), outputs(:)
        type(expr_t), intent(in) :: roots(:)
        type(kernel_ir_t) :: ir
        type(kernel_emit_spec_t) :: spec
        type(str_t) :: source
        logical :: ok
        character(:), allocatable :: message, cuda_source
        integer :: last
        call lower_kernel_ir(roots, ir, ok, message)
        if (.not. ok) then
            print *, message
            error stop 'cannot lower cell physics'
        end if
        spec%name = str(name)
        spec%args = args
        spec%outputs = outputs
        spec%temp_prefix = str('t')
        spec%generator = str('gen/generate_gpu_physics.f90')
        spec%regenerate_command = str('generate_gpu_physics SRC/generated')
        spec%target = TARGET_CUDA
        source = emit_cuda_device_ir(ir, spec, ok, message)
        if (.not. ok) then
            print *, message
            error stop 'cannot emit CUDA cell physics'
        end if
        cuda_source = chars(source)
        last = len(cuda_source)
        do while (last > 0)
            if (cuda_source(last:last) /= new_line('a')) exit
            last = last - 1
        end do
        write (cuda_unit, '(a)') cuda_source(:last)
        spec%target = TARGET_FORTRAN_CPU
        spec%pure_procedure = .true.
        source = emit_fortran_kernel_ir(ir, spec, ok, message)
        if (.not. ok) then
            print *, message
            error stop 'cannot emit Fortran cell physics'
        end if
        write (fortran_unit, '(a)') chars(source)
    end subroutine emit

    function integer_text(value) result(text)
        integer, intent(in) :: value
        character(:), allocatable :: text
        character(12) :: buffer
        write (buffer, '(i0)') value
        text = trim(buffer)
    end function integer_text

end program generate_gpu_physics
